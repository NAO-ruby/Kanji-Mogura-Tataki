const KANJI_QUESTIONS = Object.fromEntries(Object.entries(QUESTION_ROWS).map(([grade, rows]) => [
  grade, rows.map(([format, reading, answer, distractors, promptOrMeaning, explanation], index) => {
    const type = { r: "reading", m: "meaning", i: "idiom" }[format];
    const meaning = explanation ?? promptOrMeaning;
    return {
      id: grade + "-" + (index + 1), type, reading, answer,
      distractors: distractors.split(" "), meaning,
      prompt: type === "idiom" ? promptOrMeaning : type === "reading" ? reading : meaning,
      word: type === "idiom" ? promptOrMeaning.replace("□", answer) : answer
    };
  })
]));

